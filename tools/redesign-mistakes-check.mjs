import assert from 'node:assert/strict';
import path from 'node:path';
import {fileURLToPath,pathToFileURL} from 'node:url';
const root=path.resolve(process.argv.find(value=>value.startsWith('--source-root='))?.slice(14)||fileURLToPath(new URL('../',import.meta.url)));
const {mistakeMarkup}=await import(pathToFileURL(path.join(root,'public/app/mistakes.js')));
const task={item_id:'6',prompt:'Synthetic authored question?',answer_kind:'choice',options:[{id:'a',text:'Authored wrong answer',value:'a'},{id:'b',text:'Authored correct answer',value:'b'}]};
const row={evidence_id:'11111111-2222-4333-8444-555555555555',set_id:'hidden-internal-id',version:'hidden-version',section:'LV',part:2,task,material:{text:'Synthetic authored reading passage.'},your_answer:'a',correct_answer:'b'};
const text=html=>html.replace(/<[^>]+>/g,' ');
const config={examLanguage:'de',locale:'uk',uiText:()=> 'Reading'};
const markup=mistakeMarkup(row,config);
assert.ok(markup.includes(task.prompt)&&markup.includes(row.material.text));
assert.ok(markup.includes('Authored wrong answer')&&markup.includes('Authored correct answer'));
assert.ok(!text(markup).includes(row.set_id)&&!text(markup).includes(row.version));
assert.match(markup,/lang="de" dir="ltr"/);
console.log('PASS mistakes retain original context and name both answers without internal identities');
assert.match(markup, /data-mistake-retry="0"(?! disabled)/);
assert.match(mistakeMarkup({...row,task:null},config),/data-mistake-retry="0" disabled/);
assert.match(mistakeMarkup({...row,evidence_id:null},config),/data-mistake-retry="0" disabled/);
console.log('PASS retry requires both owned evidence and its original task');
const boolean=mistakeMarkup({...row,task:{...task,answer_kind:'judgement',options:[{id:'true',text:'richtig',value:true},{id:'false',text:'falsch',value:false}]},your_answer:false,correct_answer:true},config);
assert.match(boolean,/dir="ltr">falsch<\/span>/);assert.match(boolean,/dir="ltr">richtig<\/span>/);
assert.ok(!text(boolean).includes('false')&&!text(boolean).includes('true'));
console.log('PASS typed judgement mistakes display human exam-language answers');
